import fs from "node:fs";
const CDP = "http://127.0.0.1:9222";
const pages = await (await fetch(`${CDP}/json/list`)).json();
const page = pages.find((x) => x.type === "page" && x.url.includes("127.0.0.1:5173"));
const ws = new WebSocket(page.webSocketDebuggerUrl);
await new Promise((r, j) => { ws.addEventListener("open", r, { once: true }); ws.addEventListener("error", j, { once: true }); });
let id = 0; const pending = new Map(); const events = [];
ws.addEventListener("message", (e) => { const m = JSON.parse(e.data); if (m.id) { const h = pending.get(m.id); if (h) { pending.delete(m.id); m.error ? h.reject(new Error(m.error.message)) : h.resolve(m.result); } } else events.push(m); });
const send = (method, params = {}) => new Promise((r, j) => { const n = ++id; pending.set(n, { resolve: r, reject: j }); ws.send(JSON.stringify({ id: n, method, params })); });
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const evaluate = async (expression) => (await send("Runtime.evaluate", { expression, returnByValue: true, awaitPromise: true })).result?.value;
const shot = async (name) => { const s = await send("Page.captureScreenshot", { format: "png", fromSurface: true }); fs.writeFileSync(`shots/${name}.png`, Buffer.from(s.data, "base64")); };
await send("Page.enable"); await send("Runtime.enable"); await send("Network.enable");
await send("Emulation.setDeviceMetricsOverride", { width: 1440, height: 900, deviceScaleFactor: 1, mobile: false });
await send("Page.navigate", { url: "http://127.0.0.1:5173/?date=2026-10-29&region=110000&view=sidebar" });
await sleep(3500);
await evaluate(`document.querySelector('.central-tile')?.click()`);
await sleep(2200);
await evaluate(`[...document.querySelectorAll('button.central-team-row')].find(n=>n.innerText.includes('中国共产党中央委员会'))?.click()`);
await sleep(2200);
const body1 = await evaluate("document.body.innerText");
await shot("frontend-central-committee");
console.log("committee snippet", body1.slice(body1.indexOf("中国共产党中央委员会"), body1.indexOf("中国共产党中央委员会") + 900));
await evaluate(`[...document.querySelectorAll('button.central-team-row')].find(n=>n.innerText.includes('中央书记处'))?.click()`);
await sleep(1800);
