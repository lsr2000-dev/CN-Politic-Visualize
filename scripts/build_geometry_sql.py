"""Emit 03_geometry.sql: load province boundaries from the DataV GeoJSON.

The API can serve the frontend directly from public/geo/*.json, but PostGIS
needs the same polygons for spatial predicates (point-in-province, bbox
queries, future prefecture drill-down). Keeping this as SQL makes the Docker
database reproducible with no Python dependency inside the DB container.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GEO = ROOT / "frontend" / "public" / "geo" / "china-provinces.json"
OUT = ROOT / "infra" / "initdb" / "03_geometry.sql"


def main() -> None:
    data = json.loads(GEO.read_text(encoding="utf-8"))
    lines = [
        "-- AUTO-GENERATED by scripts/build_geometry_sql.py",
        "-- Province boundaries from DataV GeoAtlas (GCJ-02 aligned display copy).",
        "SET search_path = polvis, public;",
        "BEGIN;",
    ]
    count = 0
    for feature in data["features"]:
        props = feature.get("properties", {})
        code = str(props.get("adcode", ""))
        geometry = feature.get("geometry")
        if not code or not geometry:
            continue
        if len(code) != 6:
            continue
        geojson = json.dumps(geometry, ensure_ascii=False, separators=(",", ":"))
        lines.append(
            "UPDATE polvis.regions r SET geom = g.geom, "
            "centroid = ST_PointOnSurface(g.geom), bbox = ST_Envelope(g.geom) "
            "FROM (SELECT ST_Multi(ST_SetSRID("
            f"ST_GeomFromGeoJSON('{geojson}'), 4326)) AS geom) g "
            f"WHERE r.code = '{code}';"
        )
        count += 1
    lines += [
        "COMMIT;",
        "",
        f"-- {count} province geometries loaded",
        "ANALYZE polvis.regions;",
    ]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({count} features, {OUT.stat().st_size / 1024:.0f} KB)")


if __name__ == "__main__":
    main()
