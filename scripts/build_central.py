def committee_at(name: str, day: str) -> dict | None:
    records = MEMBERS.get(name) or []
    if not records:
        return None
    dated = []
    for rec in records:
        start = rec.get("start") or ""
        end = rec.get("end")
        if start and start <= day and (not end or day <= end):
            dated.append(rec)
    if dated:
        rec = sorted(dated, key=lambda r: r["term"])[-1]
        term = next(t for t in TERMS if t["ordinal"] == rec["term"])
        return {
            "term": rec["term"],
            "term_label": term["label"],
            "type": rec["type"],
            "status": "active",
            "label": label_for(term, rec["type"]),
            "status_label": "在任",
        }
    ended = [r for r in records if r.get("end") and r["end"] < day]
    if not ended:
        return None
    rec = sorted(ended, key=lambda r: (r["term"], r["end"]))[-1]
    term = next(t for t in TERMS if t["ordinal"] == rec["term"])
    status = rec.get("status", "term_ended")
    status_label = {
        "expelled": "已开除",
        "retired": "已退休",
        "deceased": "已故",
        "term_ended": "任期结束",
        "resigned": "已辞职",
    }.get(status, "已离任")
    return {
        "term": rec["term"],
        "term_label": term["label"],
        "type": rec["type"],
        "status": status,
        "label": "原" + label_for(term, rec["type"]),
        "status_label": status_label,
    }


